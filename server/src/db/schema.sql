-- Users Table
CREATE TABLE IF NOT EXISTS users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(100) NOT NULL,
  email VARCHAR(255) NOT NULL,
  password_hash VARCHAR(255) NOT NULL,
  created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_users_email_lower ON users (LOWER(email));

-- Refresh Tokens Table (Rotation, Revocation, and Reuse Detection)
CREATE TABLE IF NOT EXISTS refresh_tokens (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  token_hash VARCHAR(64) NOT NULL,
  expires_at TIMESTAMPTZ NOT NULL,
  created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
  revoked_at TIMESTAMPTZ,
  replaced_by_token_hash VARCHAR(64)
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_refresh_tokens_hash ON refresh_tokens (token_hash);
CREATE INDEX IF NOT EXISTS idx_refresh_tokens_user_id ON refresh_tokens (user_id);
CREATE INDEX IF NOT EXISTS idx_refresh_tokens_active_user ON refresh_tokens (user_id) WHERE revoked_at IS NULL;

-- Meal Slot ENUM
DO $$ BEGIN
  CREATE TYPE time_slot AS ENUM (
    'morning_fasting',
    'after_breakfast',
    'after_lunch',
    'after_dinner'
  );
EXCEPTION
  WHEN duplicate_object THEN null;
END $$;

-- Readings Table
CREATE TABLE IF NOT EXISTS readings (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  date DATE NOT NULL,
  slot time_slot NOT NULL,
  value INTEGER NOT NULL CHECK (value >= 40 AND value <= 600),
  created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uq_user_date_slot UNIQUE (user_id, date, slot)
);

CREATE INDEX IF NOT EXISTS idx_readings_user_date ON readings (user_id, date);
CREATE INDEX IF NOT EXISTS idx_readings_user_pagination ON readings (user_id, date DESC, slot ASC);
